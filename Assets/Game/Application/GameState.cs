namespace Game.Application
{
    /// <summary>
    /// Identifies the application state available in the M0 framework.
    /// </summary>
    public enum GameState
    {
        /// <summary>
        /// The application has not entered a state.
        /// </summary>
        None = 0,

        /// <summary>
        /// The empty main-menu state is active.
        /// </summary>
        MainMenu = 1
    }
}
